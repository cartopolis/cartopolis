/// The register's outline of one building, `(lat, lng)`, from PDOK's BAG WFS.
fn bag_outline(ctx: &Ctx, pand: &str, near: (f64, f64)) -> Outcome<Vec<(f64, f64)>> {
    let d = 0.0005;
    let url = format!(
        "https://service.pdok.nl/lv/bag/wfs/v2_0?service=WFS&version=2.0.0&request=GetFeature\
         &typeNames=bag:pand&outputFormat=application/json&srsName=EPSG:4326&count=50\
         &bbox={},{},{},{},EPSG:4326",
        near.0 - d,
        near.1 - d,
        near.0 + d,
        near.1 + d
    );
    let doc = http::get_json(ctx, &url, "BAG pand")?;
    let feature = doc["features"]
        .as_array()
        .into_iter()
        .flatten()
        .find(|f| f["properties"]["identificatie"].as_str() == Some(pand))
        .ok_or_else(|| PipelineError::Failed(format!("BAG has no pand {pand} there")))?;
    let ring = match feature["geometry"]["type"].as_str() {
        Some("Polygon") => &feature["geometry"]["coordinates"][0],
        Some("MultiPolygon") => &feature["geometry"]["coordinates"][0][0],
        other => {
            return Err(PipelineError::Failed(format!(
                "pand {pand}: geometry {other:?}"
            )))
        }
    };
    // GeoJSON is (lng, lat) even when the CRS is EPSG:4326.
    Ok(ring
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|p| Some((p[1].as_f64()?, p[0].as_f64()?)))
        .collect())
}

/// The cell whose LoD2.2 file draws this building's shell.
///
/// **It has to be that one.** The client skips a shell only when the lod3 file
/// of the cell drawing it lists the pand, and a cell draws a building when the
/// building's first vertex is inside it — so a model filed under any other cell
/// is drawn *inside* the shell it was meant to replace. The Euroborg sits on a
/// cell boundary, which is how this was found. Read off the published LoD2.2
/// cells; the outline's first point is the fallback when they are not there.
fn owner_cell(ctx: &Ctx, pand: &str, outline: &[(f64, f64)]) -> Cell {
    let mut candidates: Vec<Cell> = outline.iter().map(|p| lat_lng_to_cell(p.0, p.1)).collect();
    candidates.sort_unstable();
    candidates.dedup();
    for cell in candidates {
        let Some(bytes) = ctx.read_site(&cell_path("lod22", cell)) else {
            continue;
        };
        let Ok(file) = serde_json::from_slice::<File>(&bytes) else {
            continue;
        };
        if let Some(first) = file
            .elements
            .iter()
            .find(|e| e.id.0 == pand)
            .and_then(|e| e.p.first())
        {
            return lat_lng_to_cell(first.0, first.1);
        }
    }
    ctx.log(format!(
        "pand {pand}: not in any published LoD2.2 cell; filing it by its outline"
    ));
    lat_lng_to_cell(outline[0].0, outline[0].1)
}

/// The surface model, fetched with three tries: one PDOK hiccup should not cost
/// the model.
fn surface(ctx: &Ctx, plane: Plane, half: f64) -> Outcome<Surface> {
    let source = Pdok::surface();
    let mut last = String::new();
    for attempt in 0..3 {
        ctx.check()?;
        match Surface::fetch(&source, plane, half) {
            Ok(s) => return Ok(s),
            Err(e) => {
                last = e;
                ctx.log(format!("AHN surface: {last} (retry {})", attempt + 1));
                ctx.sleep(std::time::Duration::from_secs(3))?;
            }
        }
    }
    Err(PipelineError::Failed(format!("AHN surface: {last}")))
}

pub fn run(ctx: &Ctx) -> Outcome<DatasetResult> {
    let [x0, y0, x1, y1] = ctx.bbox;
    let here: Vec<&Landmark> = LANDMARKS
        .iter()
        .filter(|l| {
            let p = Pitch::of(l.pitch);
            let [x, y] = cartopolis_geo::ahn::wgs84_to_rd(p.plane.lat, p.plane.lng);
            x >= x0 && x <= x1 && y >= y0 && y <= y1
        })
        .collect();
    ctx.log(format!("{} landmark(s) in the area", here.len()));
    let mut cells: BTreeMap<Cell, File> = BTreeMap::new();
    let mut triangles = 0usize;
    for (i, landmark) in here.iter().enumerate() {
        ctx.check()?;
        ctx.progress(Progress {
            phase: Some("models".into()),
            done: Some(i as u64),
            total: Some(Some(here.len() as u64)),
        });
        let pitch = Pitch::of(landmark.pitch);
        let outline = bag_outline(ctx, landmark.pand, (pitch.plane.lat, pitch.plane.lng))?;
        let ring: Vec<[f64; 2]> = outline
            .iter()
            .map(|&(la, lo)| pitch.plane.to_en(la, lo))
            .collect();
        let reach = ring.iter().map(|p| len(*p)).fold(0.0, f64::max) + 10.0;
        let surface = surface(ctx, pitch.plane, reach)?;
        let bowl = measure(&pitch, &ring, &surface).ok_or_else(|| {
            PipelineError::Failed(format!(
                "{}: the surface model does not show a bowl round the pitch",
                landmark.name
            ))
        })?;
        let elements = build(&pitch, &bowl, landmark.pand);
        let tris: usize = elements.iter().map(|e| e.t.len()).sum();
        triangles += tris;
        let cell = owner_cell(ctx, landmark.pand, &outline);
        ctx.log(format!(
            "{}: grass at {:.2} m NAP, roof {:.1}–{:.1} m, {} elements, {tris} triangles → cell {}/{}",
            landmark.name,
            bowl.grass,
            bowl.sections.iter().map(|s| s.back_h).fold(f64::INFINITY, f64::min),
            bowl.sections.iter().map(|s| s.inner_h).fold(0.0, f64::max),
            elements.len(),
            cell.0,
            cell.1
        ));
        let file = cells.entry(cell).or_default();
        file.elements.extend(elements);
        file.pands.push(landmark.pand.to_string());
    }
    for (cell, file) in &cells {
        ctx.write_doc(&cell_path("lod3", *cell), file)?;
    }
    let pands: Vec<&str> = here.iter().map(|l| l.pand).collect();
    ctx.write_json(
        "lod3/coverage.json",
        &json!({
            "name": ctx.name,
            "zoom": CACHE_ZOOM,
            "lod": "3",
            "attribution": ATTRIBUTION,
            "source": "generated from BAG, AHN and OpenStreetMap",
            "bbox_rd": ctx.bbox,
            "cells": sorted_cells(cells.keys().copied()),
            "pands": pands,
            "model_count": here.len(),
        }),
    )?;
    Ok(DatasetResult {
        cells: cells.len(),
        counts: vec![
            Count::new("models", here.len()),
            Count::new("triangles", triangles),
        ],
    })
}

