/// Triangles in the pitch plane: points are `[east, north, height]`.
///
/// Corners are shared between the quads that meet at them — a row's tread and
/// the next row's riser have an edge in common — which halves the file. The
/// client expands every triangle itself, so sharing changes nothing it draws.
#[derive(Default)]
struct Mesh {
    p: Vec<[f64; 3]>,
    t: Vec<Tri>,
    index: std::collections::HashMap<[i64; 3], u32>,
}

impl Mesh {
    fn vertex(&mut self, q: [f64; 3]) -> u32 {
        // Keyed at a millimetre, finer than anything written out.
        let key = [
            (q[0] * 1000.0).round() as i64,
            (q[1] * 1000.0).round() as i64,
            (q[2] * 1000.0).round() as i64,
        ];
        let next = self.p.len() as u32;
        let p = &mut self.p;
        *self.index.entry(key).or_insert_with(|| {
            p.push(q);
            next
        })
    }

    fn quad(&mut self, a: [f64; 3], b: [f64; 3], c: [f64; 3], d: [f64; 3], roof: bool) {
        let [a, b, c, d] = [a, b, c, d].map(|q| self.vertex(q));
        let r = u8::from(roof);
        // A quad folded onto itself (a zero-height wall) draws nothing.
        if a != b && b != c && a != c {
            self.t.push(Tri(a, b, c, r));
        }
        if a != c && c != d && a != d {
            self.t.push(Tri(a, c, d, r));
        }
    }

    fn element(
        self,
        plane: &Plane,
        pand: &str,
        part: u32,
        class: &str,
        rgb: [u8; 3],
    ) -> Option<Element> {
        if self.t.is_empty() {
            return None;
        }
        let p = self
            .p
            .iter()
            .map(|q| {
                let (lat, lng) = plane.to_lat_lng([q[0], q[1]]);
                (round(lat, 7), round(lng, 7), round(q[2], 2) as f32)
            })
            .collect();
        Some(Element {
            class: class.into(),
            id: Id(pand.into()),
            p,
            part,
            rgb: Some(rgb),
            t: self.t,
        })
    }

    /// A level rectangle in pitch coordinates (`along`, `across`), `h` up.
    fn rect(&mut self, pitch: &Pitch, a: [f64; 2], c: [f64; 2], h: f64) {
        let p = |al: f64, ac: f64| {
            let en = pitch.en(al, ac);
            [en[0], en[1], h]
        };
        self.quad(
            p(a[0], c[0]),
            p(a[1], c[0]),
            p(a[1], c[1]),
            p(a[0], c[1]),
            true,
        );
    }

    /// A painted line from one pitch point to another, `w` wide.
    fn line(&mut self, pitch: &Pitch, from: [f64; 2], to: [f64; 2], w: f64, h: f64) {
        let d = [to[0] - from[0], to[1] - from[1]];
        let l = len(d);
        if l < 1e-9 {
            return;
        }
        let n = [-d[1] / l * w / 2.0, d[0] / l * w / 2.0];
        let p = |q: [f64; 2], s: f64| {
            let en = pitch.en(q[0] + n[0] * s, q[1] + n[1] * s);
            [en[0], en[1], h]
        };
        self.quad(p(from, -1.0), p(to, -1.0), p(to, 1.0), p(from, 1.0), true);
    }

    /// A painted arc about `centre`, radius `r`, from angle `a0` to `a1`
    /// (radians, 0 along the pitch).
    fn arc(&mut self, pitch: &Pitch, centre: [f64; 2], r: f64, a0: f64, a1: f64, w: f64, h: f64) {
        let steps = ((a1 - a0).abs() * r / 0.6).ceil().max(2.0) as usize;
        let pt = |a: f64| [centre[0] + r * a.cos(), centre[1] + r * a.sin()];
        for i in 0..steps {
            let t0 = a0 + (a1 - a0) * i as f64 / steps as f64;
            let t1 = a0 + (a1 - a0) * (i + 1) as f64 / steps as f64;
            self.line(pitch, pt(t0), pt(t1), w, h);
        }
    }
}

