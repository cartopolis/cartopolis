    /// Prints the measured Euroborg. Network: `cargo test -p cartopolis_atlas
    /// euroborg_profile -- --ignored --nocapture`.
    #[test]
    #[ignore = "fetches PDOK"]
    fn euroborg_profile() {
        let pitch = Pitch::of(EUROBORG.pitch);
        let url = "https://service.pdok.nl/lv/bag/wfs/v2_0?service=WFS&version=2.0.0&request=GetFeature&typeNames=bag:pand&outputFormat=application/json&srsName=EPSG:4326&count=20&bbox=53.2058,6.5912,53.2064,6.5920,EPSG:4326";
        let doc: serde_json::Value =
            serde_json::from_str(&ureq::get(url).call().unwrap().into_string().unwrap()).unwrap();
        let ring: Vec<[f64; 2]> = doc["features"][0]["geometry"]["coordinates"][0]
            .as_array()
            .unwrap()
            .iter()
            .map(|p| {
                pitch
                    .plane
                    .to_en(p[1].as_f64().unwrap(), p[0].as_f64().unwrap())
            })
            .collect();
        let surface = Surface::fetch(&Pdok::surface(), pitch.plane, 160.0).unwrap();
        let bowl = measure(&pitch, &ring, &surface).unwrap();
        println!("grass at {:.2} m NAP", bowl.grass);
        for s in bowl.sections.iter().step_by(4) {
            println!(
                "{:5.0}°  pitch {:5.1}  roof {:5.1}–{:5.1} at {:4.1}–{:4.1} m  ring to {:5.1} at {:4.1} m",
                s.theta.to_degrees(),
                s.pitch,
                s.inner,
                s.back,
                s.inner_h,
                s.back_h,
                s.outer,
                s.ring_h
            );
        }
        let elements = build(&pitch, &bowl, EUROBORG.pand);
        let tris: usize = elements.iter().map(|e| e.t.len()).sum();
        println!("{} elements, {tris} triangles", elements.len());
    }
