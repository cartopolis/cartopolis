//! Building models for landmarks the survey gets wrong (`docs/notes/building-models.md`).
//!
//! 3DBAG reconstructs every building as a solid shell from a laser survey flown
//! overhead, and for most buildings that is the right shape. For a stadium it is
//! not: the Euroborg comes out as one flat-topped block 23 m high over its whole
//! 34,000 m² footprint, pitch included, because the register's outline has no
//! hole in it and the reconstruction fills whatever the outline encloses.
//!
//! This dataset writes the `lod3` tree the client already streams in place of a
//! shell (`systems::lod3`): per cell, model elements plus the BAG ids they
//! replace, and a `coverage.json`. The models are **generated, not surveyed** —
//! from the register's outline, the half-metre AHN surface model (which sees the
//! roof and the open pitch), and the pitch as OpenStreetMap maps it. What none of
//! those can see is under the roof: the stands are an assumption, and every
//! constant that makes one is named as one.
//!
//! The model is approximate by design: the right footprint, heights and bowl, not
//! the architecture. A modeller's file for the same building would replace it
//! through the same tree.

